// Writes assets/blender/layout.json from the authoritative src/world/layout.ts, so the Blender
// station build places walls, doors, props and lights exactly where the game's collision is.
//   node scripts/export-layout.mjs      (Node >= 23.6 runs the TypeScript module directly)
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const L = await import(join(root, 'src/world/layout.ts'));
const out = {
  note: 'Generated by scripts/export-layout.mjs. Game space: metres, +Y up, +Z north, yaw 0 faces +Z.',
  wallT: L.WALL_T,
  ceilH: L.CEIL_H,
  eyeH: L.EYE_H,
  bodyR: L.BODY_R,
  doorOpening: { w: L.DOOR_OPENING_W, h: L.DOOR_OPENING_H },
  rects: L.RECTS,
  walls: L.computeWalls(),
  doors: L.DOORS,
  frames: L.FRAMES,
  placements: L.PLACEMENTS,
  colliders: L.staticColliders(),
  interactables: L.INTERACTABLES,
  safePoints: L.SAFE_POINTS,
  guides: L.GUIDES,
  zoneLights: L.ZONE_LIGHTS,
  signs: L.SIGNS,
};
writeFileSync(join(root, 'assets/blender/layout.json'), JSON.stringify(out, null, 1) + '\n');
console.log(`layout.json: ${out.rects.length} rects, ${out.walls.length} walls, ${out.placements.length} placements, ${out.signs.length} signs`);
